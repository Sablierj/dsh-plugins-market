/**
 * 模块 11 —— F11-08「双版本对比评估」九维的**如实登记**。
 *
 * ## 这份清单存在，是因为「跑九个维度的分」做不到，而装作做到了更糟
 *
 * 需求文档 `RESEARCH-module-alignment-v2.0.md:307`（F11-08 行）**逐字**点名九个维度：
 *
 *   事实一致 / 规则命中 / 关键词执行 / 结构完整 / 解释性 / 语气 / 稳定性 / 人工采纳率 / 成本
 *
 * 而「双版本对比」要成立，至少需要两样东西，本插件两样都没有：
 *
 *   - **不调 LLM**（全仓无任何模型调用通道）—— 没有「跑」，就没有「跑出来的结果」；
 *   - `prompt` 保存是**原地 UPDATE 覆盖**（`src/store/prompt.js:307-313`），**没有版本行**，
 *     而且 `agent_run` **无 token / 费用列**。
 *
 * 所以能交的只有**材料**：两版正文并排 + 九维清单交给**人**来对照。
 * 本仓铁律：**给缺失造一个像数据的替身，比留一个洞更危险。**
 * 九维**一格数字都不能填** —— 填了任何一个，就是这一批的全责缺陷。
 *
 * ## 关键：九维是**两种**「没有」，不能混成一句「都没有」
 *
 * 把两类折叠成一句「都没有」，本身就是「把缺失折叠成有」的镜像错误。必须分开登记：
 *
 *   - **A 有同名物，但不是本维**（① 事实一致、② 规则命中）——
 *     仓库里**有同名的东西**，但属于**别的模块 / 别的用途**，**不能挪用**。
 *     这两条最容易写错：看起来「有」，其实对象根本不对。
 *   - **B 概念未立项**（③ 关键词执行、④ 结构完整、⑤ 解释性、⑥ 语气、⑦ 稳定性）——
 *     全仓 grep **零命中**，既无表无列，也从未在 metrics / gap 里登记过。
 *   - **C 无数据来源**（⑧ 人工采纳率、⑨ 成本）——
 *     概念存在，甚至**算得出来类似的数**，但**对象不对 / 没有任何来源**。
 *     必须写成「**没有这个来源**」，**不是 0**。
 *
 * ## 与 `src/domain/agent/gap.js` 同一个形状
 *
 * `gap.js` 立好了范式（`AGENT_GAP_ELEMENTS` / `AGENT_GAP_COUNT` / `AGENT_GAP_SUMMARY`）：
 * **算不出来的东西，写「缺哪份记录」，不写「未实现」**，也不编一个像数据的替身。
 * 这份清单是同一件事在**提示词九维**这一层的展开 —— 即**模块 11 版本**。
 * 字段名与 `gap.js` 同名同义（`id` / `label` / `missing` / `source`），降低读者切换成本；
 * 本文件另加 `kind`（§1 的 A/B/C 三类）与 `sameNameAt`（仅 A 类）。
 *
 * ## 它是常量，不是查询
 *
 * 九条都是**声明**（跟着代码走），所以这里导出一个结构化常量，不碰库、不做 I/O、不写审计。
 * 谁把它渲染到哪一屏由调用方决定（当前挂在 `promptEditor` 的 `compareDimensions` 上，
 * 随提示词编辑器的 state 一起下发 —— 见 `src/web/routes.js`）。
 *
 * ## 纪律：**不许给任何一条编数字**
 *
 * 每一条回答的是「**缺哪份记录**」，不是「值是多少」。本文件里**不打任何分数 / 通过率 /
 * 百分比 / 排名**，也不出现任何表示「没有」的数字 —— 「没有」写成「没有这个来源」这几个字，
 * 不写成 0。除**特性号（`F11-08`）、模块编号（`模块 12`）、file:line 引用**这三类
 * **编号 / 坐标**之外，本文件的文案里不出现阿拉伯数字（白名单口径见断言⑤ 的注释）。
 * `tests/b11-8-version-compare.mjs` 用断言 ⑤ 钉住这一点。
 *
 * ⚠️ 断言⑤ 只查**阿拉伯数字**，不查中文数字（「命中两条」不会被抓）—— 中文数字在本仓
 * 是正常行文的一部分（「两个 id 空间不相交」「三类缺失」），一律拦会把 ⑤ 变成永远红的
 * 断言，而永远红的断言与永远绿的断言是同一类缺陷。这条**射程边界是声明的**。
 */

