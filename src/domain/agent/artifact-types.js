/**
 * 模块 12 的**约定**产物类型（F12-03 的「质量摘要」）。
 *
 * ## 「约定」这个词是这段注释的重点
 *
 * `agent_artifact.type` 是一列**自由字符串** —— 插件从没有、也不该有一个产物类型的闭集
 * （一次运行可以产出任何形状的东西）。这里声明的是一小把**被命名的**类型，用途只有一个：
 * 让读者（页面 / 会话）能**按名字**取到那一类产物，而不是靠猜字符串。
 *
 * ⚠️ 插件**不校验**产物内容，也**不强制**谁必须产出它。一个没有质量摘要的运行完全合法 ——
 * 这一版**没有 LLM 通道**，产出「质量摘要」那种分析是会话侧的事（§13 的分工）。所以任何
 * 「运行必须产出质量摘要」的说法都是插件做不到的承诺，**不许**写进文案与描述里。
 *
 * ## 与 `GATED_ARTIFACT_TYPES` 为什么分开
 *
 * `GATED_ARTIFACT_TYPES`（`src/tools/agent.js`）列的是「哪些 `type` 的写入要过门禁」——
 * 那是**写路径**的事。这里列的是「哪些 `type` 有名字」—— 那是**读路径**的事。一个 type
 * 可以在这里有名字而完全不过门禁（质量摘要就是），也可以过门禁而还没在这里命名。合成一张
 * 表会让「有名字」与「要审批」互相暗示，而它们是两个维度。
 */

/** 质量摘要（需求 §4 的第 4 项）：一次运行产出的、供人快速判断结果可不可信的那一份。 */
export const QUALITY_SUMMARY_TYPE = 'quality-summary'

/**
 * 被命名的约定类型。`note` 说明它**是什么**，不承诺它**会**出现。
 *
 * 列表本身是**开放的**（`type` 不在里面不代表非法），所以这里导出的是一个**清单**而不是
 * 一个校验用的闭集 —— 调用方按名字找，找不到就是「没这个名字」，不是「拒绝」。
 */
export const CONVENTIONAL_ARTIFACT_TYPES = [
  {
    type: QUALITY_SUMMARY_TYPE,
    label: '质量摘要',
    note: '运行时对本次结果可信度的一页说明。⚠️ 插件**不强制**产出、**不校验**内容 —— 它是会话侧的分析。',
  },
]

